"""Turn raw judge scores into the results tables (results/RESULTS.md + results/summary.json)."""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from .metrics import auroc, bootstrap_ci, rate, threshold_at_fpr

FAMILIES = ["negation", "random_swap", "real"]
LABEL = {"negation": "negation (rule flip)", "random_swap": "random swap (other patient's answer)",
         "real": "real (clinician-written MEDEC error)"}


def load(path):
    rows = [json.loads(l) for l in Path(path).read_text().splitlines()]
    by = defaultdict(dict)
    for r in rows:
        by[r["case_id"]][r["condition"]] = r
    return rows, by


def verdict(r):
    p = {"S": r["p_supported"], "NS": r["p_not_supported"], "NA": r["p_not_addressed"]}
    return max(p, key=p.get)


def summarize(path, fpr=0.10):
    rows, by = load(path)
    judge = rows[0]["judge"]
    out = {"judge": judge, "n_cases": len(by), "modes": {}}
    for mode in ("lenient", "strict"):
        # lenient = Forus design: only Not Supported flags; strict = silence collapses into Not Supported
        flag = (lambda r: verdict(r) == "NS") if mode == "lenient" else (lambda r: verdict(r) != "S")
        score = (lambda r: r["p_not_supported"]) if mode == "lenient" else (lambda r: 1 - r["p_supported"])
        clean = [by[c]["clean"] for c in by if "clean" in by[c]]
        cs = [score(r) for r in clean]
        t = threshold_at_fpr(cs, fpr)
        m = {"argmax_fp_rate": sum(map(flag, clean)) / len(clean), "threshold": t,
             "fp_at_threshold": rate(cs, t), "families": {}}
        for fam in FAMILIES:
            ids = [c for c in by if fam in by[c] and "clean" in by[c]]
            fs = [score(by[c][fam]) for c in ids]
            hits = [int(score(by[c][fam]) > t) for c in ids]
            paired_worse = sum(score(by[c][fam]) <= score(by[c]["clean"]) for c in ids) / len(ids)
            m["families"][fam] = {
                "n": len(ids),
                "argmax_detection": sum(flag(by[c][fam]) for c in ids) / len(ids),
                "auroc_vs_clean": auroc(cs, fs),
                "detection_at_fpr": sum(hits) / len(hits),
                "detection_at_fpr_ci95": bootstrap_ci(hits),
                "paired_not_higher_than_clean": paired_worse,
            }
        bytype = defaultdict(list)
        for c in by:
            if "real" in by[c]:
                bytype[by[c]["real"]["error_type"]].append(int(score(by[c]["real"]) > t))
        m["real_detection_by_type"] = {k: (sum(v) / len(v), len(v)) for k, v in sorted(bytype.items())}
        out["modes"][mode] = m
    return out


def fmt(s, fpr):
    L = [f"### {s['judge']} ({s['n_cases']} MEDEC-MS test cases)", ""]
    for mode, m in s["modes"].items():
        L.append(f"**{mode}** ({'Not Addressed does not flag' if mode == 'lenient' else 'Not Addressed counts as a flag'}). "
                 f"Argmax false-positive rate on clean claims: {m['argmax_fp_rate']:.1%}. "
                 f"Threshold for {fpr:.0%} FP on clean: {m['threshold']:.3f} (actual {m['fp_at_threshold']:.1%}).")
        L.append("")
        L.append(f"| perturbation family | n | argmax detection | AUROC vs clean | detection at {fpr:.0%} FP (95% CI) | wrong claim scored no higher than the correct one |")
        L.append("|---|---|---|---|---|---|")
        for fam, f in m["families"].items():
            lo, hi = f["detection_at_fpr_ci95"]
            L.append(f"| {LABEL[fam]} | {f['n']} | {f['argmax_detection']:.1%} | {f['auroc_vs_clean']:.3f} | "
                     f"{f['detection_at_fpr']:.1%} ({lo:.1%}-{hi:.1%}) | {f['paired_not_higher_than_clean']:.1%} |")
        L.append("")
        L.append("Real-error detection at the same threshold, by MEDEC error type: " + ", ".join(
            f"{k} {v[0]:.0%} (n={v[1]})" for k, v in m["real_detection_by_type"].items()))
        L.append("")
    return "\n".join(L)


def main():
    fpr = 0.10
    sums, parts = [], []
    for p in sorted(Path("results").glob("raw_*_test.jsonl")):
        s = summarize(p, fpr)
        sums.append(s)
        parts.append(fmt(s, fpr))
    Path("results/summary.json").write_text(json.dumps(sums, indent=1))
    Path("results/RESULTS.md").write_text("# Results (generated by `python -m mutjudge.report`)\n\n" + "\n".join(parts))
    print("\n".join(parts))


if __name__ == "__main__":
    main()
